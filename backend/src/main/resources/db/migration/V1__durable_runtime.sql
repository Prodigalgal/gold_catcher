CREATE TABLE gc_document (
    kind VARCHAR(40) NOT NULL,
    id VARCHAR(120) NOT NULL,
    body TEXT NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (kind, id)
);
CREATE INDEX gc_document_updated ON gc_document(kind, updated_at);
CREATE TABLE gc_event (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_id VARCHAR(120) NOT NULL,
    event_type VARCHAR(60) NOT NULL,
    body TEXT NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX gc_event_aggregate ON gc_event(aggregate_id, sequence);
