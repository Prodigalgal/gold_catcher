CREATE TABLE gc_market_frame (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR(40) NOT NULL,
    channel VARCHAR(60) NOT NULL,
    connection_epoch BIGINT NOT NULL,
    source_at TIMESTAMP WITH TIME ZONE,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,
    body TEXT NOT NULL
);
CREATE INDEX gc_market_frame_symbol_sequence ON gc_market_frame(symbol, sequence);
CREATE INDEX gc_market_frame_received ON gc_market_frame(received_at);
